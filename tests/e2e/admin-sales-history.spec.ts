import { expect, test } from "@playwright/test";
import { demoCatalog } from "../../src/modules/catalog/demo";

test("busca SKU, advierte stock y completa un retiro una sola vez", async ({ page, isMobile }, info) => {
  if (!isMobile) await page.setViewportSize({ width: 1440, height: 900 });
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.addInitScript((catalog) => localStorage.setItem("stylo.catalog-preview.v1", JSON.stringify({ catalog, images: {} })), demoCatalog());
  await page.goto("/vista-previa/pedidos");
  await page.getByRole("button", { name: "Crear venta o retiro" }).click();
  await page.getByLabel("Nombre del cliente", { exact: true }).fill("Retiro para probar");
  await page.getByRole("button", { name: "Agregar presentación" }).click();
  const finder = page.getByRole("combobox", { name: "Presentación 1" });
  await finder.fill("DEMO-1-B");
  await page.getByRole("listbox", { name: "Resultados para presentación 1" }).getByRole("option").first().click();
  await expect(page.locator(".admin-stock-warning[role=alert]")).toContainText("sin stock");
  await expect(page.getByRole("button", { name: "Registrar retiro pendiente" })).toBeDisabled();
  await finder.fill("DEMO-1-A");
  await page.getByRole("listbox", { name: "Resultados para presentación 1" }).getByRole("option").first().click();
  await page.getByLabel("Cantidad 1").fill("9");
  await expect(page.locator(".admin-stock-warning[role=alert]")).toContainText("quedan 8");
  await page.getByLabel("Cantidad 1").fill("2");
  await expect(page.getByRole("button", { name: "Registrar retiro pendiente" })).toBeEnabled();
  await page.getByRole("button", { name: "Registrar retiro pendiente" }).click();
  await expect(page.getByRole("table", { name: "Ventas y retiros registrados" })).toContainText("Retiro para probar");
  await page.screenshot({ path: info.outputPath(`admin-sales-table-${isMobile ? "mobile" : "desktop"}.png`), fullPage: true });
  const before = await page.evaluate(() => JSON.parse(localStorage.getItem("stylo.catalog-preview.v1")!).catalog.products[0].variants[0].stock);
  expect(before).toBe(8);
  await page.getByRole("row", { name: /Retiro para probar/ }).click();
  const dialog = page.getByRole("dialog", { name: "Detalle del registro" });
  await expect(dialog).toContainText("Chocolate");
  await dialog.screenshot({ path: info.outputPath(`admin-sales-detail-${isMobile ? "mobile" : "desktop"}.png`) });
  await dialog.getByRole("checkbox", { name: /Confirmo que cobré y entregué/ }).check();
  await dialog.getByRole("button", { name: "Marcar como retirado" }).click();
  await expect(dialog).toContainText("Retirado");
  await expect(dialog.getByRole("button", { name: "Marcar como retirado" })).toHaveCount(0);
  const after = await page.evaluate(() => JSON.parse(localStorage.getItem("stylo.catalog-preview.v1")!).catalog.products[0].variants[0].stock);
  expect(after).toBe(6);
  await page.keyboard.press("Escape");
  await page.getByRole("searchbox", { name: "Buscar cliente" }).fill("Retiro para probar");
  await page.getByRole("combobox", { name: "Estado" }).selectOption("paid");
  await expect(page.getByRole("table", { name: "Ventas y retiros registrados" })).toContainText("Retirado");
  await page.getByRole("combobox", { name: "Período" }).selectOption("previous");
  await expect(page.getByText("No hay registros para este período y filtros.")).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await page.screenshot({ path: info.outputPath(`admin-sales-history-${isMobile ? "mobile" : "desktop"}.png`), fullPage: true });
  expect(errors).toEqual([]);
});

test("reposición abre la variante correcta y el resumen conserva las estadísticas", async ({ page, isMobile }, info) => {
  if (!isMobile) await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto("/vista-previa/resumen");
  await expect(page.getByRole("heading", { name: "Facturación histórica" })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Para reponer" })).toBeVisible();
  await expect(page.getByText(/2 agotadas/)).toBeVisible();
  await page.screenshot({ path: info.outputPath(`admin-sales-summary-${isMobile ? "mobile" : "desktop"}.png`), fullPage: true });
  const restock = page.getByRole("link", { name: /Proteína de prueba.*Vainilla/ });
  await restock.click();
  await expect(page).toHaveURL(/producto=00000000-0000-4000-8000-000000000030/);
  await expect(page.locator("#variant-00000000-0000-4000-8000-000000000051")).toBeVisible();
  await expect(page.locator("#variant-00000000-0000-4000-8000-000000000051").getByLabel("Stock")).toHaveValue("0");
  const cost = page.locator("#variant-00000000-0000-4000-8000-000000000051").getByLabel("Costo de compra por unidad (ARS) · privado");
  await cost.fill("1250.50");
  await page.locator("#variant-00000000-0000-4000-8000-000000000051").getByRole("button", { name: "Guardar costo" }).click();
  await expect(page.getByRole("status").filter({ hasText: "Costo de compra guardado" })).toBeVisible();
  const savedCost = await page.evaluate(() => JSON.parse(localStorage.getItem("stylo.purchase-costs-preview.v1")!)["00000000-0000-4000-8000-000000000051"]);
  expect(savedCost).toBe(125050);
});
